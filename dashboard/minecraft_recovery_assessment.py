"""Read-only Controller recovery assessment using persisted audit and runtime health.

The audit record is not proof that the original NeoForge loader remains valid.
Fail closed until a separately verified loader attestation is available.
"""
from __future__ import annotations
from typing import Any
from datetime import datetime, timezone

from agent_instance_runtime_health_repository import AgentInstanceRuntimeHealthRepository
from universal_event_repository import UniversalEventRepository
from agent_instance_provisioning_repository import AgentInstanceProvisioningRepository

EVENT_TYPE = "MINECRAFT_SERVERPACK_MIGRATION_RECOVERED"


def _instant(value: Any) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        instant = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return instant.astimezone(timezone.utc) if instant.tzinfo else None
    except ValueError:
        return None


def recovery_assessment(backend: Any, *, instance_id: str, agent_id: str) -> dict[str, Any]:
    result = {"status": "unverified", "instance_id": instance_id, "agent_id": agent_id,
              "audit_recorded": False, "healthy": False, "loader_verified": False,
              "failure_matches_recovery": False,
              "allow_clear_previous_failure": False}
    if not instance_id or not agent_id:
        return result
    events = UniversalEventRepository(backend).list_events(
        limit=10, event_type=EVENT_TYPE, agent_id=agent_id, instance_id=instance_id)
    matching = [e for e in events if e.get("source") == "controller.authenticated_agent_recovery"
                and e.get("agent_id") == agent_id and e.get("instance_id") == instance_id]
    if not matching:
        return result
    event = matching[0]
    audit_at = _instant(event.get("occurred_at"))
    details = event.get("data")
    observed_at = _instant(details.get("observed_at")) if isinstance(details, dict) else None
    if audit_at is None or observed_at is None or observed_at < audit_at:
        return result
    result["audit_recorded"] = True
    latest = AgentInstanceProvisioningRepository(backend).latest_for_instance(instance_id)
    if not isinstance(latest, dict) or latest.get("status") != "failed":
        return result
    if latest.get("agent_id") != agent_id:
        return result
    failed_at = _instant(latest.get("completed_at") or latest.get("updated_at"))
    if failed_at is None or failed_at >= audit_at:
        return result
    result["failure_matches_recovery"] = True
    rows = AgentInstanceRuntimeHealthRepository(backend).list_for_agent(agent_id)
    observed = next((r for r in rows if r.get("instance_id") == instance_id), None)
    if not observed:
        return result
    health_at = _instant(observed.get("reported_at"))
    if health_at is None or health_at < observed_at:
        return result
    result["healthy"] = (
        str(observed.get("observed_state") or "").lower() == "running"
        and str(observed.get("reconcile_status") or "").lower() == "healthy"
        and str(observed.get("health") or "").lower() in {"healthy", "ok"}
    )
    # Only use Agent proof that passed the authenticated Controller ingestion boundary.
    result["agent_reported_loader_proof"] = bool(
        isinstance(details, dict) and details.get("agent_reported_loader_proof") is True
    )
    if result["healthy"] and result["agent_reported_loader_proof"]:
        # The loader proof was generated by the separate instance-local verifier
        # and admitted through an authenticated, ownership-checked Agent heartbeat.
        result["loader_verified"] = True
        result["allow_clear_previous_failure"] = True
        result["status"] = "recovered_verified"
    elif result["healthy"]:
        result["status"] = "awaiting_loader_proof"
    else:
        result["status"] = "awaiting_healthy_reconcile"
    return result
